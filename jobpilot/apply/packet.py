import json
import logging
from pathlib import Path
from typing import Dict, Any, Optional
from jobpilot.core.config import settings
from jobpilot.core.db import get_all_answers, update_application_status

logger = logging.getLogger("jobpilot.apply.packet")


def build_apply_packet(
    app_id: int,
    job_id: str,
    job_title: str,
    company: str,
    apply_url: str,
    resume_pdf_path: str,
    cover_note: str,
    matched_skills: list[str]
) -> Dict[str, Any]:
    """
    Builds the Assisted Apply Packet for LinkedIn, Naukri, Indeed, and external portals.
    Generates a localized packet file and structured metadata for 1-click copy in the UI.
    """
    db_answers = get_all_answers()
    answers = {k: v["value"] for k, v in db_answers.items() if "[FILL]" not in v["value"]}

    screener_answers = {
        "Notice Period": answers.get("notice_period", "Immediate / Fresher"),
        "Total Experience": answers.get("experience_years", "0-1 years (Fresher)"),
        "Current CTC": answers.get("current_ctc", "Fresher / None"),
        "Expected CTC": answers.get("expected_ctc", "4.5 - 7.5 LPA (Negotiable)"),
        "Work Authorization": answers.get("work_authorization", "Authorized to work in India (Citizen)"),
        "Requires Visa Sponsorship": answers.get("requires_visa_sponsorship", "No"),
        "Highest Degree": answers.get("highest_degree", "M.Sc. Computer Science (Machine Intelligence)"),
        "Graduation Year": answers.get("graduation_year", "2026"),
        "Willingness to Relocate": answers.get("willing_to_relocate", "Yes (Bangalore, Kochi, Thiruvananthapuram, Kozhikode, Remote India)"),
        "LinkedIn": answers.get("linkedin_url", "https://www.linkedin.com/in/aswinpt2004"),
        "GitHub": answers.get("github_url", "https://github.com/Aswinpt2004"),
        "Portfolio": answers.get("portfolio_url", "https://codedbyaswinpt.vercel.app/")
    }

    packet_dir = settings.packets_dir
    safe_comp = "".join(c for c in company if c.isalnum() or c in (' ', '_', '-')).strip().replace(' ', '_')
    packet_filename = f"packet_{safe_comp}_{job_id}.md"
    packet_path = packet_dir / packet_filename

    md_content = f"""# Assisted Apply Packet: {job_title} at {company}

**Job Link:** [{apply_url}]({apply_url})
**Tailored Resume:** [{Path(resume_pdf_path).name}]({Path(resume_pdf_path).resolve()})
**Key Skills:** {", ".join(matched_skills)}

---

## 1. Tailored Cover Note
```text
{cover_note}
```

---

## 2. Common Screener Answers
"""
    for q, a in screener_answers.items():
        md_content += f"- **{q}:** `{a}`\n"

    md_content += f"""
---
*Generated by JobPilot v2 for Aswin P T. Never automates bot clicking on LinkedIn/Naukri/Indeed.*
"""

    with open(packet_path, "w", encoding="utf-8") as f:
        f.write(md_content)

    logger.info("Saved Assisted Apply Packet to %s", packet_path)

    return {
        "packet_path": str(packet_path),
        "job_url": apply_url,
        "resume_path": resume_pdf_path,
        "cover_note": cover_note,
        "screener_answers": screener_answers
    }

